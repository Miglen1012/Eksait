export default function Terms() {
  function scrollToSection(sectionId, updateUrl = true) {
    const section = document.getElementById(sectionId);

    if (!section) {
      return;
    }

    if (updateUrl) {
      window.history.pushState(
        { ...(window.history.state || {}), __appScrollState: true, scrollY: window.scrollY },
        "",
        `/terms#${sectionId}`,
      );
    }

    section.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  useEffect(() => {
    const sectionId = window.location.hash.replace("#", "");

    if (!sectionId) {
      return undefined;
    }

    const frameId = window.requestAnimationFrame(() => scrollToSection(sectionId, false));

    return () => window.cancelAnimationFrame(frameId);
  }, []);

  return (
    <main className="container terms-page">
      <section className="page-surface terms-hero">
        <span className="page-kicker">Правна информация</span>
        <h1>Общи условия</h1>
        <p>
          Този уеб сайт (www.Eksait.com) и всички изображения, видеа, програмен код и свързана информация под формата на съдържание
          (занапред наричани „Сайт“ или „Сайтът“) са собственост на „Ексайт Къмпани“ ООД, ЕИК: 200257153, със седалище и адрес на
          управление гр. Стара Загора 6000, кв. Трите чучура 68 вх.А, ап.26.
        </p>
        <p>
          Целта на настоящите общи условия е да фиксира отношенията между „Ексайт Къмпани“ ООД (занапред наричан „Търговец“) и всички
          физически или юридически лица (занапред наричани „Клиенти“), които искат да закупят продукти, предлагани в онлайн
          пространството от Сайта.
        </p>
      </section>

      <div className="terms-layout">
        <aside className="terms-nav page-surface" aria-label="Навигация в общите условия">
          <span className="page-kicker">Раздели</span>
          {sections.map((section) => (
            <a
              href={`#${section.id}`}
              key={section.id}
              onClick={(event) => {
                event.preventDefault();
                scrollToSection(section.id);
              }}
            >
              {section.title}
            </a>
          ))}
        </aside>

        <section className="terms-content">
          {sections.map((section) => (
            <article className="page-surface terms-section" id={section.id} key={section.id}>
              <h2>{section.title}</h2>
              {section.paragraphs.map((paragraph) => (
                <p key={paragraph}>{paragraph}</p>
              ))}
            </article>
          ))}
        </section>
      </div>
    </main>
  );
}
